// Regenerates src/abi.generated.ts from the Foundry artifacts in contracts/out (run `forge build` there first).
// Usage: node scripts/gen-abi.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..')
const out = join(root, 'contracts', 'out')
const read = (file, name) => JSON.parse(readFileSync(join(out, file, `${name}.json`), 'utf8')).abi

const groups = {
  xdrc20: [['IXDRC20.sol', 'IXDRC20']],
  permit2: [['IPermit2Expiring.sol', 'IPermit2Expiring']],
  xns: [
    ['IXNS.sol', 'IENSRegistry'],
    ['IXNS.sol', 'IAddrResolver'],
    ['IXNS.sol', 'IAddressResolver'],
    ['IXNS.sol', 'ITextResolver'],
    ['IXNS.sol', 'INameResolver'],
    ['IXNS.sol', 'IVersionableResolver'],
    ['IXNS.sol', 'IXNSRegistrar'],
  ],
  vault: [['IGuardianVault.sol', 'IGuardianVault']],
  account: [['IXdevsSmartAccount.sol', 'IAccountEvents']],
  factory: [
    ['SmartAccountFactory.sol', 'SmartAccountFactory'],
    ['CanonicalTokenFactory.sol', 'CanonicalTokenFactory'],
  ],
}

const strip = (x) => {
  const o = { type: x.type, name: x.name }
  if (x.indexed !== undefined) o.indexed = x.indexed
  if (x.components) o.components = x.components.map(strip)
  if (x.inputs) o.inputs = x.inputs.map(strip)
  if (x.anonymous !== undefined) o.anonymous = x.anonymous
  return o
}

let src = '// GENERATED by scripts/gen-abi.mjs from contracts/out — do not edit by hand.\n\n'
for (const [group, files] of Object.entries(groups)) {
  const seen = new Set()
  const events = []
  for (const [file, name] of files) {
    for (const item of read(file, name)) {
      if (item.type !== 'event') continue
      const key = item.name + JSON.stringify(item.inputs.map((i) => i.type))
      if (seen.has(key)) continue
      if (group === 'factory' && !['AccountCreated', 'CanonicalTokenCreated'].includes(item.name)) continue
      seen.add(key)
      events.push(strip(item))
    }
  }
  src += `export const ${group}Events = ${JSON.stringify(events, null, 2)} as const\n\n`
}
writeFileSync(join(root, 'apps', 'indexer', 'src', 'abi.generated.ts'), src)
console.log('wrote src/abi.generated.ts')
