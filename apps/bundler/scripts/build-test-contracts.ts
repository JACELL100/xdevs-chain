// Recompiles test/contracts/*.sol with Foundry and regenerates test/test-contracts-artifact.ts (committed, so the
// tests only need anvil, not solc). Usage: npm run build:test-contracts
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = mkdtempSync(join(tmpdir(), 'xdevs-bundler-test-'))
try {
  execFileSync(
    'forge',
    [
      'build', '--root', root, '--contracts', join('test', 'contracts'), '--out', join(out, 'out'), '--cache-path', join(out, 'cache'),
      '--use', '0.8.38', '--optimize', '--optimizer-runs', '200', '--evm-version', 'cancun', '--no-metadata',
    ],
    { stdio: 'inherit' },
  )
  const art = JSON.parse(readFileSync(join(out, 'out', 'TestTogglePaymaster.sol', 'TestTogglePaymaster.json'), 'utf8')) as {
    bytecode: { object: string }
  }
  writeFileSync(
    join(root, 'test', 'test-contracts-artifact.ts'),
    `// GENERATED by scripts/build-test-contracts.ts from test/contracts/TestTogglePaymaster.sol (solc 0.8.38, optimizer 200,
// evm cancun, no metadata). Do not edit by hand: run \`npm run build:test-contracts\`.
export const TOGGLE_PAYMASTER_BYTECODE = '${art.bytecode.object}' as const
`,
  )
  console.log('wrote test/test-contracts-artifact.ts')
} finally {
  rmSync(out, { recursive: true, force: true })
}
