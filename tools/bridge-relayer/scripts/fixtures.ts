// Generates the Foundry fixtures in contracts/test/bridge/fixtures from REAL chain data (read-only):
//
//   * Sepolia: two sync-committee updates (periods P-1, P), the current finality update (period P+1), the RLP
//     header of the finalized execution block, a receipt proof and an eth_getProof storage proof in it.
//   * xDEVS testnet (Enclave, chain 717171): commit certificates, headers, a receipt proof and the validator
//     set (Staking.consensusValidatorSet()).
//
// Usage: node scripts/fixtures.ts --cache <dir> [--beacon URL] [--sepolia URL] [--xdevs URL]
// Responses are cached in <dir> so the fixtures can be regenerated byte-for-byte.

import fs from "node:fs";
import path from "node:path";
import { createPublicClient, encodeAbiParameters, http, parseAbi, type Hex } from "viem";
import { committeeFromPubkeys, SLOTS_PER_PERIOD, toContractUpdate, type LcUpdateJson } from "../src/beacon.ts";
import { headerRlp, receiptProof, type RpcBlock, type RpcReceipt } from "../src/encoding.ts";
import { committeeParams, updateParams } from "../src/abi.ts";
import { setFromStaking, STAKING_ADDRESS, toContractCommit, type CommitCertificateJson } from "../src/xdevs.ts";

const args = new Map<string, string>();
for (let i = 2; i < process.argv.length; i += 2) args.set(process.argv[i]!.replace(/^--/, ""), process.argv[i + 1]!);
const cache = args.get("cache") ?? ".fixture-cache";
const BEACON = args.get("beacon") ?? "https://lodestar-sepolia.chainsafe.io";
const SEPOLIA = args.get("sepolia") ?? "https://ethereum-sepolia-rpc.publicnode.com";
const XDEVS = args.get("xdevs") ?? "https://rpc.xdevschain.tech";
const OUT = path.resolve(import.meta.dirname, "../../../contracts/test/bridge/fixtures");
fs.mkdirSync(cache, { recursive: true });

async function cached<T>(name: string, load: () => Promise<T>): Promise<T> {
  const f = path.join(cache, name);
  if (fs.existsSync(f)) return JSON.parse(fs.readFileSync(f, "utf8")) as T;
  const v = await load();
  fs.writeFileSync(f, JSON.stringify(v));
  return v;
}

async function rpc<T>(url: string, method: string, params: unknown[]): Promise<T> {
  const res = await fetch(url, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ jsonrpc: "2.0", id: 1, method, params }),
  });
  const j = (await res.json()) as { result?: T; error?: unknown };
  if (j.error) throw new Error(`${method}: ${JSON.stringify(j.error)}`);
  return j.result as T;
}

async function beacon<T>(p: string): Promise<T> {
  const res = await fetch(BEACON + p);
  if (!res.ok) throw new Error(`${p}: ${res.status}`);
  return (await res.json()) as T;
}

const write = (name: string, v: unknown) =>
  fs.writeFileSync(path.join(OUT, name), JSON.stringify(v, (_, x) => (typeof x === "bigint" ? x.toString() : x), 1) + "\n");

// ---------------------------------------------------------------------------------------------------------------
// Sepolia
// ---------------------------------------------------------------------------------------------------------------

const finality = await cached("finality.json", async () => (await beacon<{ data: LcUpdateJson }>("/eth/v1/beacon/light_client/finality_update")).data);
const period = Math.floor(Number(finality.signature_slot) / SLOTS_PER_PERIOD);
const [u0, u1] = await cached(`updates-${period - 2}.json`, async () =>
  (await beacon<{ data: LcUpdateJson }[]>(`/eth/v1/beacon/light_client/updates?start_period=${period - 2}&count=2`)).map((x) => x.data),
);
const genesis = await cached("genesis.json", async () => (await beacon<{ data: { genesis_time: string; genesis_validators_root: Hex } }>("/eth/v1/beacon/genesis")).data);
const forks = await cached("forks.json", async () => (await beacon<{ data: { epoch: string; current_version: Hex }[] }>("/eth/v1/config/fork_schedule")).data);

// Trusted checkpoint: the committee of period P-1 (= next committee of update P-2).
const c1 = committeeFromPubkeys(u0!.next_sync_committee!.pubkeys, u0!.next_sync_committee!.aggregate_pubkey);
const c2 = committeeFromPubkeys(u1!.next_sync_committee!.pubkeys, u1!.next_sync_committee!.aggregate_pubkey);
const rot = toContractUpdate(u1!, c1, true);
const fin = toContractUpdate(finality, c2, false);

const execHash = finality.finalized_header.execution_block_hash;
const block = await cached("exec-block.json", () => rpc<RpcBlock>(SEPOLIA, "eth_getBlockByHash", [execHash, false]));
const receipts = await cached("exec-receipts.json", () => rpc<RpcReceipt[]>(SEPOLIA, "eth_getBlockReceipts", [block.number]));
const txIndex = receipts.findIndex((r) => r.status === "0x1" && r.logs.length > 0);
const logged = receipts[txIndex]!;
const sepoliaClient = createPublicClient({ transport: http(SEPOLIA) });
// Default: the Sepolia USDC balance slot of the recipient of a transfer in this block (any slot works).
const storageAccount = (args.get("storage-account") ?? "0x1c7d4b196cb0c7b01d743fbc6116a902379c7238") as Hex;
const storageSlot = (args.get("storage-slot") ?? "0xe58fc8b03dee9b1a577786d9537a779479411f15bf2f325d893067f74d0a6ae1") as Hex;
const proof = await cached("exec-proof.json", () =>
  sepoliaClient.getProof({ address: storageAccount, storageKeys: [storageSlot], blockNumber: BigInt(block.number) }),
);

write("sepolia.json", {
  source: { beacon: BEACON, executionRpc: SEPOLIA, note: "real Sepolia data, generated by tools/bridge-relayer/scripts/fixtures.ts" },
  genesisValidatorsRoot: genesis.genesis_validators_root,
  genesisTime: Number(genesis.genesis_time),
  forkEpochs: forks.map((f) => Number(f.epoch)),
  forkVersions: forks.map((f) => f.current_version),
  gloasForkEpoch: Number(forks[forks.length - 1]!.epoch),
  checkpointPeriod: period - 1,
  checkpointCommitteeRoot: c1.root,
  nextCommitteeRoot: c2.root,
  committeeP1: encodeAbiParameters(committeeParams, [c1.keys]),
  committeeP2: encodeAbiParameters(committeeParams, [c2.keys]),
  rotationUpdate: encodeAbiParameters(updateParams, [rot.update, rot.nonSigners] as never),
  rotationNonSigners: rot.nonSigners.length,
  finalityUpdate: encodeAbiParameters(updateParams, [fin.update, fin.nonSigners] as never),
  finalityNonSigners: fin.nonSigners.length,
  finalizedSlot: Number(finality.finalized_header.beacon.slot),
  signatureSlot: Number(finality.signature_slot),
  executionBlockHash: execHash,
  executionBlockNumber: Number(block.number),
  executionHeaderRlp: headerRlp(block),
  stateRoot: block.stateRoot,
  receiptsRoot: block.receiptsRoot,
  receipt: {
    txIndex,
    proof: receiptProof(receipts, txIndex, block.receiptsRoot),
    emitter: logged.logs[0]!.address,
    topic0: logged.logs[0]!.topics[0],
    data: logged.logs[0]!.data,
  },
  storage: {
    account: storageAccount,
    slot: storageSlot,
    value: proof.storageProof[0]!.value,
    accountProof: proof.accountProof,
    storageProof: proof.storageProof[0]!.proof,
    storageHash: proof.storageHash,
  },
});

// ---------------------------------------------------------------------------------------------------------------
// xDEVS testnet
// ---------------------------------------------------------------------------------------------------------------

const xdevs = createPublicClient({ transport: http(XDEVS) });
const chainId = await cached("x-chainid.json", async () => Number(await xdevs.getChainId()));
const [ops, keys, powers] = await cached("x-set.json", async () => {
  const r = await xdevs.readContract({
    address: STAKING_ADDRESS,
    abi: parseAbi(["function consensusValidatorSet() view returns (address[], bytes32[], uint256[])"]),
    functionName: "consensusValidatorSet",
  });
  return [r[0], r[1], r[2].map(String)] as const;
});
const set = setFromStaking(keys as Hex[], powers.map(BigInt));
// Height 67 holds the testnet's only transaction so far (a receipt to prove); the second is a recent block.
const heights = [67, Number(args.get("xdevs-height") ?? 43535)];
const commits = [];
for (const h of heights) {
  const hex = `0x${h.toString(16)}`;
  const cert = await cached(`x-cert-${h}.json`, () => rpc<CommitCertificateJson>(XDEVS, "xdevs_getCommitCertificate", [hex]));
  const blk = await cached(`x-block-${h}.json`, () => rpc<RpcBlock>(XDEVS, "eth_getBlockByNumber", [hex, false]));
  const all = toContractCommit(cert, set, false);
  const quorum = toContractCommit(cert, set, true);
  const entry: Record<string, unknown> = {
    height: h,
    round: all.round,
    blockHash: cert.blockHash,
    allSigs: all.sigs,
    quorumSigs: quorum.sigs,
    headerRlp: headerRlp(blk),
    stateRoot: blk.stateRoot,
    receiptsRoot: blk.receiptsRoot,
  };
  if (h === 67) {
    const rcs = await cached(`x-receipts-${h}.json`, () => rpc<RpcReceipt[]>(XDEVS, "eth_getBlockReceipts", [hex]));
    entry.receiptProof = receiptProof(rcs, 0, blk.receiptsRoot);
  }
  commits.push(entry);
}
write("xdevs-testnet.json", {
  source: { rpc: XDEVS, note: "real xDEVS testnet (Enclave) data, read-only; generated by tools/bridge-relayer/scripts/fixtures.ts" },
  chainId,
  operators: ops,
  stakingKeys: keys,
  stakingPowersWei: powers,
  validators: set.map((v) => ({ key: v.key, power: Number(v.power) })),
  commits,
});
console.log(`fixtures written to ${OUT}: sepolia period ${period}, xdevs heights ${heights.join(", ")}`);
